from typing import Any, Dict, List, Optional

from modules.concept_extractor import ExtractedConcept
from modules.concept_graph import ConceptGraphResult
from modules.summarizer import SummaryResult


def export_summary_txt(
    summary: SummaryResult,
    metadata: Dict[str, Any],
    filename: str = "document.pdf",
) -> str:
    """
    Formats the 3-bullet research summary and detailed theory crux as a plain-text document.
    """
    output = io.StringIO()
    title = metadata.get("title", filename)
    author = metadata.get("author", "Not specified")
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    output.write("=" * 76 + "\n")
    output.write(f"PAPERLENS — RESEARCH PAPER ANALYSIS & THEORETICAL CRUX REPORT\n")
    output.write("=" * 76 + "\n")
    output.write(f"Document: {filename}\n")
    output.write(f"Title:    {title}\n")
    output.write(f"Author:   {author}\n")
    output.write(f"Date:     {now_str}\n")
    output.write(f"Method:   {summary.summary_type}\n")
    output.write("-" * 76 + "\n\n")

    if not summary.is_success:
        output.write(f"Notice: {summary.error_message or 'No summary available.'}\n")
    else:
        output.write("PART 1: EXECUTIVE THREE-BULLET RESEARCH SUMMARY & HIGHLIGHTS\n")
        output.write("-" * 55 + "\n\n")
        for idx, bullet in enumerate(summary.bullets, 1):
            output.write(f"{idx}. [{bullet.category.upper()}] (Page {bullet.page_number})\n")
            output.write(f"   \"{bullet.text}\"\n")
            output.write(f"   [Semantic Centrality Score: {bullet.centrality_score:.3f}]\n\n")

        if summary.theory_crux and summary.theory_crux.sections:
            output.write("\n" + "=" * 76 + "\n")
            output.write("PART 2: COMPREHENSIVE THEORY CRUX BREAKDOWN\n")
            output.write("=" * 76 + "\n\n")

            for sec in summary.theory_crux.sections:
                output.write(f"## {sec.title.upper()}\n")
                output.write(f"   Context: {sec.description}\n\n")
                for p_idx, pt in enumerate(sec.crux_points, 1):
                    output.write(f"   * [{p_idx}] (Page {pt.page_number}) \"{pt.text}\"\n")
                output.write("\n")

    output.write("-" * 76 + "\n")
    output.write("Note: This is an extractive AI-assisted report generated by PaperLens.\n")
    output.write("All sentences are directly extracted from the original document.\n")
    output.write("=" * 76 + "\n")

    return output.getvalue()


def export_summary_md(
    summary: SummaryResult,
    metadata: Dict[str, Any],
    filename: str = "document.pdf",
) -> str:
    """
    Formats the research summary and detailed theory breakdown as GitHub Flavored Markdown.
    """
    title = metadata.get("title", filename)
    author = metadata.get("author", "Not specified")
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        f"# 📄 PaperLens Research Summary & Theoretical Crux Report",
        f"",
        f"**Document:** `{filename}`  ",
        f"**Title:** {title}  ",
        f"**Author(s):** {author}  ",
        f"**Generated:** {now_str}  ",
        f"**Pipeline:** `{summary.summary_type}`  ",
        f"",
        f"---",
        f"",
        f"## 🎯 Part 1: Executive Highlights",
        f"",
    ]

    if not summary.is_success:
        lines.append(f"> ⚠️ **Notice:** {summary.error_message or 'No summary available.'}")
    else:
        for idx, b in enumerate(summary.bullets, 1):
            lines.extend([
                f"### {b.icon} {idx}. {b.category}",
                f"",
                f"> \"{b.text}\"",
                f"",
                f"- **Source:** Page {b.page_number} ({b.section_hint} Section)",
                f"- **Semantic Centrality Score:** `{b.centrality_score:.3f}`",
                f"",
            ])

        if summary.theory_crux and summary.theory_crux.sections:
            lines.extend([
                f"---",
                f"",
                f"## 📚 Part 2: Detailed Theory in Crux Form",
                f"",
            ])

            for sec in summary.theory_crux.sections:
                lines.extend([
                    f"### {sec.icon} {sec.title}",
                    f"*{sec.description}*",
                    f"",
                ])
                for pt in sec.crux_points:
                    lines.append(f"- **[Page {pt.page_number}]** \"{pt.text}\" *(Score: `{pt.centrality_score:.3f}`)*")
                lines.append("")

    lines.extend([
        f"---",
        f"",
        f"*Generated automatically using [PaperLens](https://github.com/paperlens) — Extractive Semantic Research Paper Analyzer.*",
    ])

    return "\n".join(lines)


def export_concepts_csv(concepts: List[ExtractedConcept]) -> str:
    """
    Serializes extracted concepts into a structured CSV format.
    """
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow([
        "Concept_ID",
        "Concept_Name",
        "Relevance_Score",
        "Frequency",
        "N_Gram_Type",
        "Theoretical_Crux",
        "Primary_Page",
        "Top_Passage_Sample",
    ])

    for c in concepts:
        primary_page = c.top_passages[0].page_number if c.top_passages else "N/A"
        sample_passage = c.top_passages[0].text if c.top_passages else ""
        writer.writerow([
            c.concept_id,
            c.text,
            f"{c.relevance_score:.3f}",
            c.frequency,
            c.n_gram_type,
            c.theoretical_crux,
            primary_page,
            sample_passage,
        ])

    return output.getvalue()


def export_graph_json(
    graph_res: ConceptGraphResult,
    metadata: Dict[str, Any],
) -> str:
    """
    Serializes NetworkX graph nodes and edges to standard Node-Link JSON format.
    """
    data = {
        "metadata": {
            "title": metadata.get("title", "Research Paper"),
            "author": metadata.get("author", "Unknown"),
            "nodes_count": graph_res.metrics.total_nodes,
            "edges_count": graph_res.metrics.total_edges,
            "density": graph_res.metrics.density,
        },
        "nodes": graph_res.node_list,
        "edges": graph_res.edge_list,
    }
    return json.dumps(data, indent=2)


def export_graph_edges_csv(edge_list: List[Dict[str, Any]]) -> str:
    """
    Serializes graph edges to CSV format for external network tools (Gephi, Cytoscape).
    """
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow(["Source", "Target", "Semantic_Similarity", "Type"])

    for edge in edge_list:
        writer.writerow([
            edge["source"],
            edge["target"],
            edge["similarity"],
            "Undirected",
        ])

    return output.getvalue()


